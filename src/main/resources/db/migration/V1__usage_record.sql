-- Журнал всех обращений к провайдерам (каждая попытка, включая неуспешные и failover).
CREATE TABLE usage_record (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider          VARCHAR(64)  NOT NULL,
    model             VARCHAR(128),
    prompt_tokens     INTEGER,
    completion_tokens INTEGER,
    total_tokens      INTEGER,
    status            INTEGER      NOT NULL,
    latency_ms        BIGINT       NOT NULL,
    error             VARCHAR(1000),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_usage_record_created_at ON usage_record (created_at);
CREATE INDEX idx_usage_record_provider_created_at ON usage_record (provider, created_at);
